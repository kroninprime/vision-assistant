from datetime import datetime
from pathlib import Path
import textwrap

from app.main import assistant

OUTPUT_DIR = Path.home() / "Desktop" / "jarvis-sites"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def build_site(prompt: str) -> str:
    # naive HTML generator: wrap the request in a simple template
    content = (
        prompt.replace("build a site", "")
        .replace("create a site", "")
        .replace("make website", "")
        .replace("generate page", "")
        .replace("portfolio", "Portfolio")
        .replace("game", "Game")
        .strip()
    )
    if not content:
        return "Tell me what the site should say."
    ts = datetime.now().strftime("%Y%m%d-%H%M%S")
    filename = OUTPUT_DIR / f"site-{ts}.html"
    html = textwrap.dedent(
        f"""
        <!doctype html>
        <html>
        <head>
          <meta charset="utf-8" />
          <meta name="viewport" content="width=device-width, initial-scale=1" />
          <title>Jarvis Site</title>
          <style>
            body {{ font-family: 'Segoe UI', sans-serif; padding: 40px; background: #0c111b; color: #e8f1ff; }}
            h1 {{ color: #5ae0ff; }}
            section {{ margin-bottom: 16px; padding: 16px; background: rgba(255,255,255,0.05); border-radius: 12px; }}
          </style>
        </head>
        <body>
          <h1>{content.title()}</h1>
          <section>
            <p>This page was generated by Jarvis from your prompt: <strong>{content}</strong></p>
          </section>
        </body>
        </html>
        """
    )
    filename.write_text(html, encoding="utf-8")
    return f"Created site at {filename}. Opening now."


assistant.register("site builder", ["build a site", "create a site", "make website", "generate page"], build_site)
